#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""prepare_consistency.py — 为 esp-tflite-micro+ESP-NN 生成 PC/板上一致性测试向量
================================================================================
用途:
  1. 从 pc_tools/ecg_dl/models/deploy_match/mit_deploy_causal_match.npz 选择
     固定 200 拍 (100 正常 + 100 异常, random seed 42)。
  2. 用 PC TFLite Runtime 对同一批输入跑 exp7c_int8，保存每拍 abnormal 概率。
  3. 导出 INT8 C 数组到 experiments/esp_tflm_bench/main/test_vectors.h，
     供 ESP32-S3 固件逐拍推理并回传板端输出。

验收:
  - PC 输出保存为 experiments/esp_tflm_bench/consistency_pc.json
  - C 数组可被 esp_tflm_bench 编译链接
输出:
  - main/test_vectors.h
  - consistency_pc.json
"""
import json
import sys
import time
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
CACHE = REPO / "pc_tools" / "ecg_dl" / "models" / "deploy_match" / "mit_deploy_causal_match.npz"
TFLITE = REPO / "pc_tools" / "ecg_dl" / "models" / "ecg_model_exp7c_int8.tflite"
OUT_JSON = Path(__file__).resolve().parent / "consistency_pc.json"
OUT_HEADER = Path(__file__).resolve().parent / "main" / "test_vectors.h"

SEED = 42
N_PER_CLASS = 100
N_TOTAL = N_PER_CLASS * 2


def softmax(x):
    e = np.exp(x - x.max(axis=-1, keepdims=True))
    return e / e.sum(axis=-1, keepdims=True)


def load_selection():
    d = np.load(CACHE)
    beats = d["beats"]
    labels = d["labels"].astype(np.int32)
    record_ids = d["record_ids"].astype(np.int32)
    rng = np.random.default_rng(SEED)
    idx_norm = rng.choice(np.flatnonzero(labels == 0), N_PER_CLASS, replace=False)
    idx_abn = rng.choice(np.flatnonzero(labels == 1), N_PER_CLASS, replace=False)
    idx = np.concatenate([idx_norm, idx_abn])
    return beats[idx], labels[idx], record_ids[idx], idx


def pc_predict(beats):
    import tensorflow as tf
    from tensorflow.lite.python.interpreter import OpResolverType
    # 使用 TFLite BUILTIN_REF（不启用 XNNPACK delegate），与 MCU TFLite Micro 的
    # 参考/优化整数 kernel 更可比；默认 XNNPACK 在 PC 上会引入不同的量化卷积累加顺序。
    interp = tf.lite.Interpreter(
        model_path=str(TFLITE),
        experimental_op_resolver_type=OpResolverType.BUILTIN_REF,
        num_threads=1,
    )
    interp.allocate_tensors()
    in_d = interp.get_input_details()[0]
    out_d = interp.get_output_details()[0]
    in_scale = float(in_d["quantization_parameters"]["scales"].flatten()[0])
    in_zp = int(in_d["quantization_parameters"]["zero_points"].flatten()[0])
    out_scale = float(out_d["quantization_parameters"]["scales"].flatten()[0])
    out_zp = int(out_d["quantization_parameters"]["zero_points"].flatten()[0])
    print(f"[PC] input scale={in_scale:.8f} zp={in_zp}, output scale={out_scale:.8f} zp={out_zp}")

    quantized = np.zeros((len(beats), 250), dtype=np.int8)
    p_single = []
    p_double = []
    raw_q = []
    for i, b in enumerate(beats):
        xf = b.astype(np.float32)[None, :, None]
        xq = np.clip(np.round(xf / in_scale) + in_zp, -128, 127).astype(np.int8)
        quantized[i] = xq[0, :, 0]
        interp.set_tensor(in_d["index"], xq)
        if interp.invoke() != None:
            raise RuntimeError("invoke failed")
        q = interp.get_tensor(out_d["index"])[0].astype(np.float32)
        raw_q.append(q.astype(np.int8).tolist())
        p = (q - out_zp) * out_scale
        p1 = float(p[1])
        p_single.append(p1)
        p_double.append(float(softmax(p[None, :])[0, 1]))
        if (i + 1) % 50 == 0:
            print(f"  PC {i+1}/{len(beats)}")
    return {
        "quantized": quantized,
        "p_single": np.array(p_single, dtype=np.float64),
        "p_double": np.array(p_double, dtype=np.float64),
        "raw_q": np.array(raw_q, dtype=np.int8),
        "in_scale": in_scale,
        "in_zp": in_zp,
        "out_scale": out_scale,
        "out_zp": out_zp,
    }


def write_header(quantized, labels):
    lines = []
    lines.append("// Auto-generated by experiments/esp_tflm_bench/prepare_consistency.py")
    lines.append(f"// Source: mit_deploy_causal_match.npz, seed={SEED}, {N_PER_CLASS} normal + {N_PER_CLASS} abnormal")
    lines.append("#ifndef TEST_VECTORS_H")
    lines.append("#define TEST_VECTORS_H")
    lines.append("#include <stdint.h>")
    lines.append(f"static constexpr int kTestCount = {len(labels)};")
    lines.append("static const int16_t kTestLabels[kTestCount] = {")
    for i in range(0, len(labels), 16):
        lines.append("  " + ", ".join(str(int(x)) for x in labels[i:i+16]) + ",")
    lines.append("};")
    lines.append("static const int8_t kTestInputs[kTestCount][250] = {")
    for row in quantized:
        lines.append("  {" + ", ".join(str(int(x)) for x in row) + "},")
    lines.append("};")
    lines.append("#endif // TEST_VECTORS_H")
    OUT_HEADER.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    t0 = time.time()
    beats, labels, record_ids, indices = load_selection()
    print(f"[select] {len(beats)} beats: normal={int((labels==0).sum())} abnormal={int((labels==1).sum())}, seed={SEED}")
    res = pc_predict(beats)
    write_header(res["quantized"], labels)
    output = {
        "meta": {
            "date": time.strftime("%Y-%m-%d %H:%M:%S"),
            "source_cache": str(CACHE.relative_to(REPO)),
            "model": str(TFLITE.relative_to(REPO)),
            "selection": {"seed": SEED, "n_normal": N_PER_CLASS, "n_abnormal": N_PER_CLASS},
            "pc_semantics": "INT8 dequantized output directly (output tensor already contains Softmax; no second softmax)",
            "pc_script": str(Path(__file__).relative_to(REPO)),
            "pc_op_resolver": "BUILTIN_REF (XNNPACK disabled; matches TFLM integer kernel family)",
        },
        "indices": indices.tolist(),
        "record_ids": record_ids.tolist(),
        "labels": labels.tolist(),
        "input_quant": {"scale": res["in_scale"], "zero_point": res["in_zp"]},
        "output_quant": {"scale": res["out_scale"], "zero_point": res["out_zp"]},
        "p_single": res["p_single"].tolist(),
        "p_double": res["p_double"].tolist(),
        "raw_output": res["raw_q"].tolist(),
    }
    OUT_JSON.write_text(json.dumps(output, indent=2, ensure_ascii=False))
    print(f"[done] PC {len(beats)} probabilities saved to {OUT_JSON.relative_to(REPO)}")
    print(f"[done] header {OUT_HEADER.relative_to(REPO)} ({OUT_HEADER.stat().st_size} bytes)")
    print(f"[time] {time.time()-t0:.1f}s")


if __name__ == "__main__":
    main()
