#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""build_v6a_dataset.py -- build the 100k balanced v6a fine-tune dataset.

Selection:
  - 50k normal: stratified from v3-A hard-normal pool (score > 0.5), quotas
    by source so AFDB does not dominate.
  - 50k abnormal: stratified from all train-safe abnormal beats, also by source
    quotas.
The dataset is written as models/deploy_match/v6a_train_100k.npz.

No val/test contact. No training here.
"""
import json
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from data.split_guard import get_guard
from data.patient_split import patient_level_split, SEED as SPLIT_SEED

BASE = Path(__file__).resolve().parent
CACHE = BASE / "models" / "deploy_match"
ECG_DATA = Path("/home/devcontainers/ecg_data")
OUT = CACHE / "v6a_train_100k.npz"
SEED = 42

# Normal quotas per source; sum = 50000.
NORMAL_QUOTA = {
    0: 8000,   # MIT-BIH
    1: 8000,   # INCART
    2: 500,    # PTB (few hard normals)
    3: 10000,  # SVDB
    4: 10000,  # VFDB+CUDB
    5: 13935,  # AFDB fill remainder
}
ABNORMAL_QUOTA = {
    0: 10000,
    1: 8000,
    2: 10000,
    3: 8000,
    4: 8000,
    5: 6000,
}


def load_source_arrays(code):
    if code == 0:
        tag = "mit_bih"
        b = np.load(ECG_DATA / f"{tag}_processed_deploy_causal_beats.npy", mmap_mode="r")
        l = np.load(ECG_DATA / f"{tag}_processed_deploy_causal_labels.npy", mmap_mode="r")
        r = np.load(ECG_DATA / f"{tag}_processed_deploy_causal_record_ids.npy", mmap_mode="r")
        mask = np.asarray(get_guard(tag).train_mask, dtype=bool)
        return b, l, r, mask
    if code == 1:
        tag = "incart"
        b = np.load(ECG_DATA / f"{tag}_processed_deploy_causal_beats.npy", mmap_mode="r")
        l = np.load(ECG_DATA / f"{tag}_processed_deploy_causal_labels.npy", mmap_mode="r")
        r = np.load(ECG_DATA / f"{tag}_processed_deploy_causal_record_ids.npy", mmap_mode="r")
        mask = np.asarray(get_guard(tag).train_mask, dtype=bool)
        return b, l, r, mask
    if code == 2:
        tag = "ptb"
        b = np.load(ECG_DATA / f"{tag}_processed_deploy_causal_beats.npy", mmap_mode="r")
        l = np.load(ECG_DATA / f"{tag}_processed_deploy_causal_labels.npy", mmap_mode="r")
        r = np.load(ECG_DATA / f"{tag}_processed_deploy_causal_record_ids.npy", mmap_mode="r")
        mask = np.asarray(get_guard(tag).train_mask, dtype=bool)
        return b, l, r, mask
    if code == 3:
        tag = "svdb"
        b = np.load(ECG_DATA / f"{tag}_processed_deploy_causal_beats.npy", mmap_mode="r")
        l = np.load(ECG_DATA / f"{tag}_processed_deploy_causal_labels.npy", mmap_mode="r")
        r = np.load(ECG_DATA / f"{tag}_processed_deploy_causal_record_ids.npy", mmap_mode="r")
        mask = np.asarray(get_guard(tag).train_mask, dtype=bool)
        return b, l, r, mask
    if code == 4:
        d = np.load(CACHE / "vfdb_processed_deploy_causal.npz")
        b, l, r = d["beats"], d["labels"], d["record_ids"]
        vfdb_split = json.loads((CACHE / "vfdb_split_audit.json").read_text(encoding="utf-8"))
        train_ids = np.asarray(vfdb_split["train_record_ids"], dtype=np.int64)
        mask = np.isin(np.asarray(r, dtype=np.int64), train_ids)
        return b, l, r, mask
    if code == 5:
        d = np.load(CACHE / "afdb_processed_deploy_causal.npz")
        b, l, r = d["beats"], d["labels"], d["record_ids"]
        r = np.asarray(r, dtype=np.int64)
        pmap = {int(rid): f"afdb_{int(rid)}" for rid in np.unique(r)}
        mask = np.asarray(patient_level_split(r, pmap, seed=SPLIT_SEED)[0], dtype=bool)
        return b, l, r, mask
    raise ValueError(code)


def rng_choice(arr, n, rng):
    return rng.choice(arr, n, replace=False)


def main():
    CACHE.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    rng = np.random.default_rng(SEED)

    # Load hard-normal metadata generated by mine_hard_normal.py.
    scores_all = np.load(CACHE / "beat_pool_normal_scores.npy")
    meta = np.load(CACHE / "beat_pool_normal_meta.npz")
    src_all = meta["source"]
    rec_all = meta["record_id"]
    loc_all = meta["local_beat_index"]

    # Build selected normal entries.
    normal_sel = []
    for code, quota in NORMAL_QUOTA.items():
        cand = np.flatnonzero((src_all == code) & (scores_all > 0.5))
        n_use = min(quota, len(cand))
        if n_use <= 0:
            print(f"[V6D] normal source {code}: quota={quota} available={len(cand)} -> 0")
            continue
        pick = rng_choice(cand, n_use, rng)
        normal_sel.append(pick)
        print(f"[V6D] normal source {code}: quota={quota} available={len(cand)} -> {n_use}")
    normal_idx = np.concatenate(normal_sel)
    print(f"[V6D] normal selected total={len(normal_idx)}")

    # Build selected abnormal entries.
    abnormal_sel = []
    for code, quota in ABNORMAL_QUOTA.items():
        b, l, r, mask = load_source_arrays(code)
        cand = np.flatnonzero(mask & (np.asarray(l) == 1))
        n_use = min(quota, len(cand))
        if n_use <= 0:
            print(f"[V6D] abnormal source {code}: quota={quota} available={len(cand)} -> 0")
            continue
        pick = rng_choice(cand, n_use, rng)
        abnormal_sel.append((code, pick))
        print(f"[V6D] abnormal source {code}: quota={quota} available={len(cand)} -> {n_use}")

    # Group normal global indices by source.
    normal_by_code = {}
    for gi in normal_idx:
        code = int(src_all[gi])
        normal_by_code.setdefault(code, []).append(gi)

    # Assemble X/y/meta in per-source chunks.
    xs, ys, srcs, recs, locs, scores = [], [], [], [], [], []
    for code in sorted(set(list(NORMAL_QUOTA.keys()) + [c for c, _ in abnormal_sel])):
        b, l, r, mask = load_source_arrays(code)
        r_arr = np.asarray(r)
        if code in normal_by_code:
            globs = np.asarray(normal_by_code[code], dtype=np.int64)
            locs_use = loc_all[globs].astype(np.int64)
            x_chunk = np.asarray(b)[locs_use].astype(np.float32)
            xs.append(x_chunk)
            ys.append(np.zeros(len(locs_use), dtype=np.int32))
            srcs.append(np.full(len(locs_use), code, dtype=np.int32))
            recs.append(r_arr[locs_use].astype(np.int32))
            locs.append(locs_use.astype(np.int32))
            scores.append(scores_all[globs].astype(np.float32))
        # Abnormal chunk (appended after normal per source; source order stable).
        ab_picks = [p for c, p in abnormal_sel if c == code]
        if ab_picks:
            picks = np.asarray(ab_picks[0], dtype=np.int64)
            x_chunk = np.asarray(b)[picks].astype(np.float32)
            xs.append(x_chunk)
            ys.append(np.ones(len(picks), dtype=np.int32))
            srcs.append(np.full(len(picks), code, dtype=np.int32))
            recs.append(r_arr[picks].astype(np.int32))
            locs.append(picks.astype(np.int32))
            scores.append(np.full(len(picks), -1.0, dtype=np.float32))

    x = np.concatenate(xs).astype(np.float32)
    y = np.concatenate(ys).astype(np.int32)
    source = np.concatenate(srcs).astype(np.int32)
    record = np.concatenate(recs).astype(np.int32)
    local = np.concatenate(locs).astype(np.int32)
    score = np.concatenate(scores).astype(np.float32)

    np.savez_compressed(OUT, x=x, y=y, source=source,
                        record_id=record, local_beat_index=local,
                        hard_normal_score=score)
    print(f"[V6D] saved {OUT.name}: x={x.shape} y_norm={int((y==0).sum())} "
          f"y_abn={int((y==1).sum())} elapsed={time.time()-t0:.1f}s", flush=True)
    # Per-source counts.
    for c in range(6):
        m = source == c
        print(f"[V6D] source {c}: n={int(m.sum())} norm={int((m & (y==0)).sum())} "
              f"abn={int((m & (y==1)).sum())}", flush=True)


if __name__ == "__main__":
    main()
